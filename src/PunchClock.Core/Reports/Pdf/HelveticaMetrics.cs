    /// <summary>The WinAnsi byte for <paramref name="c"/>, or '?' for a character the standard fonts cannot show.</summary>
    public static byte Encode(char c) => c switch
    {
        >= ' ' and <= '~' => (byte)c,
        >= '\u00A0' and <= '\u00FF' => (byte)c,
        _ when Windows1252High.TryGetValue(c, out var b) => b,
        _ => (byte)'?',
    };

    public static byte[] Encode(string text)
    {
        var bytes = new byte[text.Length];
        for (var i = 0; i < text.Length; i++)
        {
            bytes[i] = Encode(text[i]);
        }

        return bytes;
    }

    /// <summary>Width of <paramref name="text"/> in points at <paramref name="size"/>.</summary>
    public static double Width(string text, bool bold, double size)
    {
        var widths = bold ? Bold : Regular;
        var total = 0;
        foreach (var c in text)
        {
            total += widths[Encode(c) - 32];
        }

        return total * size / 1000;
    }
